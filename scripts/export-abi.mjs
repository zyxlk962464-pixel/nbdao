import { readFileSync, writeFileSync } from 'node:fs';
const a = JSON.parse(readFileSync('packages/contracts/out/NBDAOSeller.sol/NBDAOSeller.json', 'utf8'));
writeFileSync('packages/shared/src/executor-abi.ts', '// Generated by pnpm contracts:build.\nexport const executorAbi = '+JSON.stringify(a.abi,null,2)+' as const;\n');
console.log('Executor ABI exported');
const opening = JSON.parse(readFileSync('packages/contracts/out/NBDAOOpeningSeller.sol/NBDAOOpeningSeller.json', 'utf8'));
writeFileSync('packages/shared/src/opening-executor-abi.ts', '// Generated by pnpm contracts:build.\nexport const openingExecutorAbi = '+JSON.stringify(opening.abi,null,2)+' as const;\n');
console.log('Opening executor ABI exported');
